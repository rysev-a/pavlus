-- Phone Retail CRM: normalized schema, in its own Postgres schema `phone_crm`
-- (the pool sets search_path to it, so every name below is unqualified).
-- Idempotent: running it again changes nothing. `reset.ts` drops the schema first.
-- Mirrors ui-kit/frontend/templates/phone-retail-crm/entities.ts:
--   * RESTRICT where the UI has a delete guard (role -> users, manufacturer -> models,
--     model -> products, product -> order items, category -> shops, user/shop -> orders)
--   * CASCADE where the UI cleans up (user -> sessions, permission -> role_permissions)
--   * SET NULL where the UI rewrites to 0 (shop -> budget; NULL is "the company", 0 on the wire)

CREATE SCHEMA IF NOT EXISTS phone_crm;
SET search_path TO phone_crm;

CREATE TABLE IF NOT EXISTS roles (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  description text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS permissions (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        text NOT NULL UNIQUE,
  description text NOT NULL DEFAULT '',
  module      text NOT NULL
);

-- Role.permissionIds: `position` keeps the order of the array.
CREATE TABLE IF NOT EXISTS role_permissions (
  role_id       integer NOT NULL REFERENCES roles (id) ON DELETE CASCADE,
  permission_id integer NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,
  position      integer NOT NULL,
  PRIMARY KEY (role_id, permission_id)
);
CREATE INDEX IF NOT EXISTS role_permissions_permission_idx ON role_permissions (permission_id);

CREATE TABLE IF NOT EXISTS users (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       text NOT NULL,
  email      text NOT NULL UNIQUE,
  phone      text NOT NULL DEFAULT '',
  role_id    integer NOT NULL REFERENCES roles (id) ON DELETE RESTRICT,
  status     text NOT NULL CHECK (status IN ('active', 'blocked', 'invited')),
  created_at date NOT NULL
);
CREATE INDEX IF NOT EXISTS users_role_idx ON users (role_id);

CREATE TABLE IF NOT EXISTS sessions (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  ip         text NOT NULL,
  device     text NOT NULL,
  started_at timestamp NOT NULL,
  expires_at timestamp NOT NULL,
  active     boolean NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_user_idx ON sessions (user_id);

CREATE TABLE IF NOT EXISTS manufacturers (
  id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name    text NOT NULL,
  country text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS models (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  manufacturer_id integer NOT NULL REFERENCES manufacturers (id) ON DELETE RESTRICT,
  name            text NOT NULL,
  year            integer NOT NULL
);
CREATE INDEX IF NOT EXISTS models_manufacturer_idx ON models (manufacturer_id);

CREATE TABLE IF NOT EXISTS products (
  id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  model_id  integer NOT NULL REFERENCES models (id) ON DELETE RESTRICT,
  sku       text NOT NULL UNIQUE,
  color     text NOT NULL DEFAULT '',
  price     numeric(12, 2) NOT NULL CHECK (price >= 0),
  processor text NOT NULL DEFAULT '',
  ram       integer NOT NULL CHECK (ram >= 0),
  storage   integer NOT NULL CHECK (storage >= 0),
  display   text NOT NULL DEFAULT '',
  stock     integer NOT NULL CHECK (stock >= 0)
);
CREATE INDEX IF NOT EXISTS products_model_idx ON products (model_id);

CREATE TABLE IF NOT EXISTS shop_categories (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  description text NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS shops (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  category_id integer NOT NULL REFERENCES shop_categories (id) ON DELETE RESTRICT,
  city        text NOT NULL DEFAULT '',
  address     text NOT NULL DEFAULT '',
  lat         double precision NOT NULL CHECK (lat BETWEEN -90 AND 90),
  lng         double precision NOT NULL CHECK (lng BETWEEN -180 AND 180),
  phone       text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS shops_category_idx ON shops (category_id);

CREATE TABLE IF NOT EXISTS orders (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    integer NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
  shop_id    integer NOT NULL REFERENCES shops (id) ON DELETE RESTRICT,
  status     text NOT NULL CHECK (status IN ('new', 'paid', 'shipped', 'delivered', 'cancelled', 'refunded')),
  created_at date NOT NULL,
  total      numeric(12, 2) NOT NULL CHECK (total >= 0),
  note       text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS orders_user_idx ON orders (user_id);
CREATE INDEX IF NOT EXISTS orders_shop_idx ON orders (shop_id);
CREATE INDEX IF NOT EXISTS orders_created_idx ON orders (created_at);
CREATE INDEX IF NOT EXISTS orders_status_idx ON orders (status);

-- Order.items: `position` keeps the order of the array.
CREATE TABLE IF NOT EXISTS order_items (
  order_id   integer NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  position   integer NOT NULL,
  product_id integer NOT NULL REFERENCES products (id) ON DELETE RESTRICT,
  qty        integer NOT NULL CHECK (qty > 0),
  price      numeric(12, 2) NOT NULL CHECK (price >= 0),
  PRIMARY KEY (order_id, position)
);
CREATE INDEX IF NOT EXISTS order_items_product_idx ON order_items (product_id);

CREATE TABLE IF NOT EXISTS budget (
  id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  month   text NOT NULL CHECK (month ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
  kind    text NOT NULL CHECK (kind IN ('income', 'salary', 'supply', 'delivery')),
  amount  numeric(12, 2) NOT NULL,
  shop_id integer REFERENCES shops (id) ON DELETE SET NULL,
  note    text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS budget_month_idx ON budget (month);
CREATE INDEX IF NOT EXISTS budget_shop_idx ON budget (shop_id);

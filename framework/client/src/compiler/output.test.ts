import { describe, expect, test } from "vitest";
import { toHtml } from "../runtime/vnode.ts";
import { compileTemplate, compileToView } from "./mod.ts";

describe("generated module is readable", () => {
  const src = `ul.list
  for user in users key user.id
    li.item(class:on=user.on @click=pick(user.id)) {user.name}`;
  const out = compileTemplate(src, { filename: "/some/where/users.pavlus" });

  test("helpers are imported from the runtime, not pasted into the module", () => {
    expect(out).toMatch(/^\/\/ Generated by pavlus from users\.pavlus\./); // file name only, no path
    expect(out).toMatch(
      /import \{[^}]*\bdiffKeyedList\b[^}]*\} from "@pavlus\/client\/runtime";/,
    );
    expect(out).not.toMatch(/function (toText|toAttr|diffKeyedList|\$list)/);
    expect(out).not.toMatch(/const \$[a-z]+ =/);
  });

  test("only the helpers a template uses are imported", () => {
    const tiny = compileTemplate("p static", {});
    expect(tiny).not.toContain("import {");
    expect(compileTemplate("p {x}", {})).toContain("import { toText } from");
  });

  test("the runtime module is configurable", () => {
    expect(
      compileTemplate("p {x}", { runtime: "/src/runtime/helpers.ts" }),
    ).toContain('import { toText } from "/src/runtime/helpers.ts";');
  });

  test("variables are named after the template", () => {
    for (const name of [
      "userList",
      "prevUserList",
      "nextUserKeys",
      "userSuffix",
      "liChildren",
      "liAttrs",
      "liEvents",
      "prevClass",
    ]) {
      expect(out, name).toMatch(new RegExp(`\\b${name}\\b`));
    }
    // no cryptic generated names like x0 / lp3 / c12
    expect(out).not.toMatch(/\b(x|y|c|a|lp|ln|kp|kn|it|sfx|bp|bn)\d+\b/);
  });

  test("blocks are commented with the template line and what they read", () => {
    expect(out).toContain("// line 1: <ul.list>");
    expect(out).toContain("// line 2: for user");
    expect(out).toMatch(/\/\/ line 3: <li\.item> \(reads: [^)]*\)/);
  });

  test("code is indented, one statement per line", () => {
    const longest = Math.max(...out.split("\n").map((l) => l.length));
    expect(longest).toBeLessThan(220);
    expect(out).toMatch(/\n {2}const nodes = \[\];\n/);
    expect(out).toMatch(/\n {2}const userList = /);
  });

  test("names are reused in sibling blocks and numbered only where the JS scope is shared", () => {
    const siblings = compileTemplate(`if a\n  p one\nif b\n  p two`, {});
    // each `if` is rendered in render() and again in diff(): four blocks in
    // all, and every one of them can call its variable pChildren
    expect(siblings.match(/const pChildren = \[\];/g)).toHaveLength(4);
    expect(siblings).not.toContain("pChildren2");
    // the same block: the second li must be numbered
    const same = compileTemplate(`ul\n  li a\n  li b`, {});
    expect(same).toContain("const liChildren = [];");
    expect(same).toContain("const liChildren2 = [];");
  });
});

describe("template names never clash with the generated code", () => {
  test("loop variables named like JS keywords, helpers or generated names", () => {
    const view = compileToView(
      `ul
  for class in classes key class
    li {class}
  for toText in texts key toText
    li {toText}
  for state in states key state
    li {state}
  for nodes in groups key nodes
    li {nodes}`,
    );
    const state = {
      classes: ["a", "b"],
      texts: ["c"],
      states: ["d"],
      groups: ["e"],
    };
    expect(toHtml(view.render(state))).toBe(
      `<ul><li>a</li><li>b</li><li>c</li><li>d</li><li>e</li></ul>`,
    );
    // and diff, which uses the same names on both sides
    const next = {
      classes: ["b", "z"],
      texts: ["c", "q"],
      states: [],
      groups: ["e", "f"],
    };
    expect(view.diff(state, next).length).toBeGreaterThan(0);
  });

  test("an imported component named like a generated name is rejected up front", () => {
    expect(() => compileToView(`import Map from "./m.pavlus"\n+Map#m`)).toThrow(
      /cannot be used/,
    );
  });
});

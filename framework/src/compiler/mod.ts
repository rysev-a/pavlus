import { parse } from "../template/parser.ts";
import { TemplateError } from "../template/errors.ts";
import type { TemplateAst } from "../template/ast.ts";
import type { View } from "../runtime/vnode.ts";
import * as runtime from "../runtime/helpers.ts";
import { generate } from "./codegen.ts";

/** Where compiled templates import their runtime helpers from. */
export const DEFAULT_RUNTIME = "@service-laboratory/pavlus/runtime";

export interface CompileOptions {
  /** Used in error messages and in the header of the generated module. */
  filename?: string;
  /** Module the helpers are imported from. Default: {@link DEFAULT_RUNTIME}. */
  runtime?: string;
}

interface Built {
  ast: TemplateAst;
  code: string;
  helpers: string[];
}

function build(source: string, opts: CompileOptions): Built {
  try {
    const ast = parse(source);
    return { ast, ...generate(ast) };
  } catch (e) {
    if (e instanceof TemplateError && opts.filename) {
      const err = new TemplateError(e.message, e.line, e.col);
      err.message = `${opts.filename}: ${e.message}`;
      throw err;
    }
    throw e;
  }
}

function importLine(names: string[], from: string): string {
  const oneLine = `import { ${names.join(", ")} } from ${JSON.stringify(from)};`;
  if (oneLine.length <= 100) return oneLine;
  return `import {\n${names.map((n) => `  ${n},`).join("\n")}\n} from ${JSON.stringify(from)};`;
}

/**
 * Compiles template source to a readable ES module exporting `render`, `diff`
 * and `meta` (and a default `{ render, diff, meta }` view). The runtime
 * helpers it uses are imported from {@link CompileOptions.runtime}, and the
 * template's own `import` lines become imports of the child views.
 */
export function compileTemplate(
  source: string,
  opts: CompileOptions = {},
): string {
  const { ast, code, helpers } = build(source, opts);
  const file = opts.filename?.split(/[\\/]/).pop() ?? "a template";
  const lines = [
    `// Generated by pavlus from ${file}. Edit the template, not this file.`,
  ];
  if (helpers.length)
    lines.push(importLine(helpers, opts.runtime ?? DEFAULT_RUNTIME));
  for (const i of ast.imports)
    lines.push(`import ${i.local} from ${JSON.stringify(i.from)};`);
  lines.push(
    "",
    code,
    "",
    "export { render, diff, meta };",
    "export default { render, diff, meta };",
    "",
  );
  return lines.join("\n");
}

/** A view, or a component object that has one. */
type ViewSource = View | { view?: View };

/**
 * Compiles and instantiates a template at runtime (tests, tooling).
 * `components` supplies the views the template imports, by local name.
 */
export function compileToView<S = any>(
  source: string,
  opts: { components?: Record<string, ViewSource> } = {},
): View<S> {
  const { ast, code } = build(source, {});
  const components = opts.components ?? {};
  const names = ast.imports.map((i) => i.local);
  const views = names.map((n) => {
    const c = components[n] as ViewSource | undefined;
    const v = c && ("render" in c ? c : c.view);
    if (!v)
      throw new Error(
        `pavlus: template imports "${n}" but no view was given in { components }`,
      );
    return v;
  });
  const helperNames = Object.keys(runtime);
  const helperValues = helperNames.map(
    (n) => (runtime as Record<string, unknown>)[n],
  );
  return new Function(
    ...helperNames,
    ...names,
    `${code}\nreturn { render, diff, meta };`,
  )(...helperValues, ...views) as View<S>;
}

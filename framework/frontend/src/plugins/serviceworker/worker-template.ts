export type CacheStrategy =
  | "cache-first"
  | "network-first"
  | "stale-while-revalidate";

export interface WorkerSourceOptions {
  /** URLs fetched into the cache on install. */
  precache?: string[];
  /**
   * Routing for GET requests. A string applies to everything; the object form
   * adds per-route strategies, tried in order, `pattern` being a RegExp source
   * tested against the full request URL.
   */
  strategy?:
    | CacheStrategy
    | {
        default?: CacheStrategy;
        routes?: { pattern: string; strategy: CacheStrategy }[];
      };
  /** Cache version. Changing it makes `activate` drop the old caches. */
  version: string;
  /** Cache name prefix (default "pavlus"). Only caches with this prefix are cleaned up. */
  prefix?: string;
}

/**
 * Source text of a small service worker, ready to be emitted as `/sw.js`.
 *
 * - install: precaches `precache` into `<prefix>-<version>` (no automatic skipWaiting)
 * - activate: deletes other `<prefix>-*` caches, claims clients, tells them `{type:"ACTIVATED", version}`
 * - fetch: GET requests only, by strategy (cache-first / network-first / stale-while-revalidate)
 * - message: `{type:"SKIP_WAITING"}` calls skipWaiting(); `{type:"GET_VERSION"}` answers the sender
 *   with `{type:"VERSION", version}`; anything else is relayed to every other client
 */
export function workerSource(o: WorkerSourceOptions): string {
  const s = o.strategy ?? "stale-while-revalidate";
  const cfg = {
    version: o.version,
    prefix: o.prefix ?? "pavlus",
    precache: o.precache ?? [],
    default:
      typeof s === "string" ? s : (s.default ?? "stale-while-revalidate"),
    routes: typeof s === "string" ? [] : (s.routes ?? []),
  };
  for (const r of [cfg.default, ...cfg.routes.map((x) => x.strategy)])
    if (!["cache-first", "network-first", "stale-while-revalidate"].includes(r))
      throw new Error(`pavlus/serviceworker: unknown strategy "${r}"`);
  for (const r of cfg.routes) new RegExp(r.pattern); // fail early on a bad pattern
  // JSON is valid JS; U+2028/2029 are escaped for older parsers.
  const json = JSON.stringify(cfg).replace(
    new RegExp("[\\u2028\\u2029]", "g"),
    (c) => "\\u" + c.charCodeAt(0).toString(16),
  );
  return `// generated by pavlus/serviceworker workerSource
"use strict";
const CONFIG = ${json};
const CACHE = CONFIG.prefix + "-" + CONFIG.version;
const ROUTES = CONFIG.routes.map((r) => ({ re: new RegExp(r.pattern), strategy: r.strategy }));

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(CONFIG.precache)),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((names) =>
        Promise.all(
          names
            .filter((n) => n.startsWith(CONFIG.prefix + "-") && n !== CACHE)
            .map((n) => caches.delete(n)),
        ),
      )
      .then(() => self.clients.claim())
      .then(() => broadcast({ type: "ACTIVATED", version: CONFIG.version })),
  );
});

function broadcast(data, except) {
  return self.clients.matchAll({ includeUncontrolled: true }).then((all) => {
    for (const c of all) if (!except || c.id !== except) c.postMessage(data);
  });
}

function strategyFor(url) {
  for (const r of ROUTES) if (r.re.test(url)) return r.strategy;
  return CONFIG.default;
}

function store(request, response) {
  if (response && response.ok) {
    const copy = response.clone();
    return caches.open(CACHE).then((c) => c.put(request, copy));
  }
}

function fromNetwork(request) {
  return fetch(request).then((response) => {
    store(request, response);
    return response;
  });
}

const strategies = {
  "cache-first": (request) =>
    caches.match(request).then((hit) => hit || fromNetwork(request)),
  "network-first": (request) =>
    fromNetwork(request).catch(() =>
      caches.match(request).then((hit) => {
        if (hit) return hit;
        return Response.error();
      }),
    ),
  "stale-while-revalidate": (request, event) =>
    caches.match(request).then((hit) => {
      const update = fromNetwork(request);
      if (hit) {
        update.catch(() => {});
        if (event && event.waitUntil) event.waitUntil(update.catch(() => {}));
        return hit;
      }
      return update;
    }),
};

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || !/^https?:/.test(request.url)) return;
  event.respondWith(strategies[strategyFor(request.url)](request, event));
});

self.addEventListener("message", (event) => {
  const data = event.data;
  if (data && data.type === "SKIP_WAITING") {
    self.skipWaiting();
  } else if (data && data.type === "GET_VERSION") {
    if (event.source) event.source.postMessage({ type: "VERSION", version: CONFIG.version });
  } else {
    event.waitUntil(broadcast(data, event.source && event.source.id));
  }
});
`;
}

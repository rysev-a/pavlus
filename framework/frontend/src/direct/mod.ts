/**
 * The `direct` compiler: the same template language and AST as the vdom
 * pipeline (`@pavlus/frontend/compiler`), compiled to ONE function
 * per template that builds DOM from a cloned static skeleton and returns a
 * block with an `u(state)` that writes only what changed. See README.md.
 *
 * @module
 */

import type { TemplateAst } from "../template/ast.ts";
import { TemplateError } from "../template/errors.ts";
import { parse } from "../template/parser.ts";
import { generateDirect, HELPERS } from "./generate.ts";
import type { DirectView } from "./runtime.ts";
import * as runtime from "./runtime.ts";

export type { Block, DirectView, Env, Rt } from "./runtime.ts";

/** Where compiled direct templates import their runtime helpers from. */
export const DIRECT_RUNTIME = "@pavlus/frontend/direct/runtime";

export interface DirectCompileOptions {
  /** Template syntax: text to AST. Default: the native indentation syntax. */
  parser?: (source: string) => TemplateAst;
  /** Used in error messages and in the header of the generated module. */
  filename?: string;
  /** Module the helpers are imported from. Default: {@link DIRECT_RUNTIME}. */
  runtime?: string;
}

function build(source: string, opts: DirectCompileOptions) {
  try {
    const ast = (opts.parser ?? parse)(source);
    return { ast, ...generateDirect(ast) };
  } catch (e) {
    if (e instanceof TemplateError && opts.filename) {
      const err = new TemplateError(e.message, e.line, e.col);
      err.message = `${opts.filename}: ${e.message}`;
      throw err;
    }
    throw e;
  }
}

function importLine(names: string[], from: string): string {
  const oneLine = `import { ${names.join(", ")} } from ${JSON.stringify(from)};`;
  if (oneLine.length <= 100) return oneLine;
  return `import {\n${names.map((n) => `  ${n},`).join("\n")}\n} from ${JSON.stringify(from)};`;
}

/**
 * Compiles template source to an ES module exporting `create` and `meta`
 * (and a default `{ create, meta }` view).
 */
export function compileDirectTemplate(
  source: string,
  opts: DirectCompileOptions = {},
): string {
  const { ast, code, helpers } = build(source, opts);
  const file = opts.filename?.split(/[\\/]/).pop() ?? "a template";
  const lines = [
    `// Generated by pavlus (direct) from ${file}. Edit the template, not this file.`,
  ];
  if (helpers.length)
    lines.push(importLine(helpers, opts.runtime ?? DIRECT_RUNTIME));
  for (const i of ast.imports)
    lines.push(`import ${i.local} from ${JSON.stringify(i.from)};`);
  lines.push(
    "",
    code,
    "",
    "export { create, meta };",
    "export default { create, meta };",
    "",
  );
  return lines.join("\n");
}

type ViewSource = DirectView | { view?: DirectView };

/**
 * Compiles and instantiates a direct template at runtime (tests, tooling).
 * `components` supplies the views the template imports, by local name.
 */
export function compileDirectToView<S = any>(
  source: string,
  opts: {
    components?: Record<string, ViewSource>;
    parser?: (source: string) => TemplateAst;
  } = {},
): DirectView<S> {
  const { ast, code } = build(source, { parser: opts.parser });
  const components = opts.components ?? {};
  const names = ast.imports.map((i) => i.local);
  const views = names.map((n) => {
    const c = components[n] as ViewSource | undefined;
    // A component's view wins; a member named `create` (a child, a handler)
    // must not be mistaken for a direct view.
    const view = (c as { view?: unknown } | undefined)?.view;
    const v =
      c &&
      (view !== undefined
        ? view
        : typeof (c as { create?: unknown }).create === "function"
          ? c
          : undefined);
    if (!v)
      throw new Error(
        `pavlus: template imports "${n}" but no view was given in { components }`,
      );
    return v;
  });
  const helperNames = HELPERS;
  const helperValues = helperNames.map(
    (n) => (runtime as Record<string, unknown>)[n],
  );
  return new Function(
    ...helperNames,
    ...names,
    `${code}\nreturn { create, meta };`,
  )(...helperValues, ...views) as DirectView<S>;
}

// A whole project from a design: the generated server and its tests, and what it
// takes to run them (package.json, tsconfig, a Postgres for development, the
// environment, a README). `scripts/flow-generate.ts` writes it to a folder. Pure.
import { type GenFile, generateServer, generateTests } from "./codegen.ts";
import { type Model, slugify } from "./model.ts";
import { usedCustom } from "./plugins.ts";

export interface ProjectOptions {
  /** the name of the package; the name of the design by default */
  name?: string;
  /** the port the server listens on */
  port?: number;
  /** the port of the Postgres of compose.yaml on this machine */
  dbPort?: number;
}

const json = (v: unknown): string => `${JSON.stringify(v, null, 2)}\n`;

export function generateProject(
  source: Model,
  o: ProjectOptions = {},
): GenFile[] {
  const name = slugify(o.name ?? source.name);
  const port = o.port ?? 3020;
  const dbPort = o.dbPort ?? 54330;
  const db = name.replace(/-/g, "_");
  const hasDb = Object.keys(source.db).length > 0;
  const file = (path: string, title: string, code: string): GenFile => ({
    path,
    group: "project",
    title,
    code,
  });
  const routes = generateServer(source)
    .filter((f) => f.path === "server/routes.ts")
    .flatMap((f) =>
      [...f.code.matchAll(/"([A-Z]+ \/[^"]*)":/g)].map((m) => m[1]),
    );
  return [
    ...generateServer(source),
    ...generateTests(source),
    file(
      "package.json",
      "package.json",
      json({
        name,
        private: true,
        version: "0.1.0",
        description: `${source.name}: a @pavlus/backend app generated by Flow Studio from its design`,
        type: "module",
        scripts: {
          start: "node --env-file-if-exists=.env server/main.ts",
          "db:up": "docker compose up -d",
          "db:down": "docker compose down",
          test: "vitest run",
          typecheck: "tsc --noEmit",
        },
        dependencies: {
          "@pavlus/frontend": "*",
          "@pavlus/backend": "*",
          pg: "^8.16.3",
        },
        devDependencies: {
          "@types/node": "^24.0.0",
          "@types/pg": "^8.15.0",
          typescript: "^7.0.2",
          vitest: "^5.0.5",
        },
      }),
    ),
    file(
      "tsconfig.json",
      "tsconfig.json",
      json({
        compilerOptions: {
          target: "ES2022",
          lib: ["ES2023", "DOM"],
          module: "ESNext",
          moduleResolution: "Bundler",
          allowImportingTsExtensions: true,
          strict: true,
          noEmit: true,
          isolatedModules: true,
          erasableSyntaxOnly: true,
          skipLibCheck: true,
          types: ["node"],
        },
        include: ["server/**/*.ts", "tests/**/*.ts"],
      }),
    ),
    ...(hasDb
      ? [
          file(
            "compose.yaml",
            "compose.yaml",
            `# Postgres for development: \`docker compose up -d\`
services:
  db:
    image: postgres:16-alpine
    environment:
      POSTGRES_USER: app
      POSTGRES_PASSWORD: app
      POSTGRES_DB: ${db}
    ports:
      - "127.0.0.1:${dbPort}:5432"
    volumes:
      - db-data:/var/lib/postgresql/data

volumes:
  db-data:
`,
          ),
          file(
            ".env.example",
            ".env.example",
            `DATABASE_URL=postgres://app:app@127.0.0.1:${dbPort}/${db}\nPORT=${port}\n`,
          ),
        ]
      : [file(".env.example", ".env.example", `PORT=${port}\n`)]),
    file(
      "README.md",
      "README.md",
      `# ${source.name}

A [@pavlus/backend](../server) app. It was **generated by Flow Studio** from the design
of the same name: the pure handlers are \`server/modules/\`, the routes \`server/routes.ts\`,
the wiring \`server/main.ts\`${hasDb ? ", the tables \`server/schema.sql\` and their starting rows \`server/seed.ts\`" : ""}.
The design is the source: change it in Flow Studio and generate again
(\`node ui-kit/scripts/flow-generate.ts <demo> <folder>\`).

\`\`\`sh
${hasDb ? "cp .env.example .env && npm run db:up   # Postgres on port " + dbPort + "\n" : ""}npm start                          # http://127.0.0.1:${port}
npm test
\`\`\`

## Routes

${routes.map((r) => `- \`${r}\``).join("\n")}
${
  usedCustom(source).length
    ? `\n## Plugins of the design\n\n${usedCustom(source)
        .map(
          (p) =>
            `- \`server/plugins/${p.name}.ts\`: ${p.about || p.name} (a stub: replace the TODOs with the real client)`,
        )
        .join("\n")}\n`
    : ""
}`,
    ),
  ];
}
